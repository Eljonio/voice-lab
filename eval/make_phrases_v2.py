def main():
    phrases, errs = [], []

    def add(pid, lang, cat, src, review=0):
        t = numbers_kk(src) if re.search(r"\d", src) else src
        t, probs = normalize(t)
        if probs:
            errs.append(f"{pid}: {probs} | {t}")
        x = dict(id=pid, lang=lang, cat=cat, text=t)
        if t != src:
            x["src"] = src
        if review:
            x["review"] = 1
        phrases.append(x)
    for cat, xs in KK.items():
        for i, s in enumerate(xs, 1):
            add(f"kk_{cat}{i:02d}", "kk", cat, s, review=cat in ("bot", "num"))
    for i, s in enumerate(MIX, 1):
        add(f"mix{i:02d}", "mix", "mix", s)
    for i, s in enumerate(RU, 1):
        add(f"ru{i:02d}", "ru", "ru", s)
    for i, (lg, s) in enumerate(BRANDS, 1):
        add(f"br{i:02d}", lg, "brand", s)
    dialogs = []
    for d, (lg, turns) in enumerate(DIALOGS, 1):
        ids = []
        for j, s in enumerate(turns, 1):
            pid = f"dlg{d}_{j}"
            add(pid, lg, "dialog", s)
            ids.append(pid)
        dialogs.append(dict(id=f"dlg{d}", lang=lg, turns=ids))
    kk_text = " ".join(p["text"].lower() for p in phrases if p["lang"] == "kk")
    cnt = Counter(ch for ch in kk_text if ch in SPECIAL)
    for ch in SPECIAL:
        if cnt[ch] < 5:
            errs.append(f"буква {ch}: {cnt[ch]} раз < 5")
    for p in phrases:
        if p["cat"] == "long" and not 25 <= len(p["text"].split()) <= 40:
            errs.append(f"{p['id']}: {len(p['text'].split())} слов вне 25–40")
    n = Counter(p["cat"] for p in phrases)
    out = dict(
        version="v2", made="2026-10-09", frozen=False,
        note="Набор оценки голоса v3. Не менять после заморозки: новые трудные фразы — в phrases_regress.json. review=1 — вычитать носителем.",
        voice=json.loads((HERE / "phrases.json").read_text())["voice"],
        protocol=dict(seeds=[1, 2, 3], cfg=2.0, timesteps=10, modes=["ref_kk", "design", "dialog_context"],
                      ref_kk="eval/ref_kk.wav — казахский женский эталон 8–12 с (выбирается на слух; в репозиторий не входит)",
                      ref_ru_legacy="eval/ref.wav — только для сравнения с историей"),
        counts=dict(n), special_letters=dict(cnt), phrases=phrases, dialogs=dialogs)
    (HERE / "phrases_v2.json").write_text(json.dumps(out, ensure_ascii=False, indent=1))
    print(f"фраз {len(phrases)}: {dict(n)}; особые буквы: {dict(cnt)}")
    for p in phrases:
        if "src" in p:
            print(f"  {p['id']}: {p['src']}  →  {p['text']}")
    if errs:
        print("ОШИБКИ:\n  " + "\n  ".join(errs))
        sys.exit(1)


if __name__ == "__main__":
    main()
